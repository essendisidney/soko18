/**
 * Generated demo people. Shown only in local/dev (no Supabase) or when NEXT_PUBLIC_DEMO_SEED=1.
 * Paying members must never be shown made-up profiles.
 */
export const DEMO_SEED_ENABLED =
  !(process.env.NEXT_PUBLIC_SUPABASE_URL && process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY) ||
  process.env.NEXT_PUBLIC_DEMO_SEED === "1";

export const PROFILES: SeedProfile[] = DEMO_SEED_ENABLED ? DEMO_PROFILES : [];

